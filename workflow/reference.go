package workflow

import (
	"fmt"
	"strings"
)

// Reference returns the step reference as Markdown (docs/STEP_REFERENCE.md),
// written from the step descriptors.
func Reference() string {
	c := Describe()
	items := map[string]ItemInfo{}
	for _, it := range c.Items {
		items[it.Type] = it
	}
	var w strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&w, format, a...) }
	p("# Step reference\n\n")
	p("<!-- Generated by workflow.Reference from the step descriptors in workflow/steps_info.go. -->\n\n")
	p("Every step a workflow can use, with its settings and a starting example.\n")
	p("[WORKFLOWS.md](WORKFLOWS.md) explains how steps fit together, expressions and the output section.\n")
	p("The engine uses the same step descriptors to generate editor metadata.\n\n")

	for _, cat := range Categories {
		var in []StepInfo
		for _, s := range c.Steps {
			if s.Category == cat {
				in = append(in, s)
			}
		}
		if len(in) == 0 {
			continue
		}
		p("- **%s:**", cat)
		for i, s := range in {
			if i > 0 {
				p(",")
			}
			p(" [`%s`](#%s)", s.Op, s.Op)
		}
		p("\n")
	}
	p("- [Expression helpers](#expression-helpers)\n\n")

	for _, cat := range Categories {
		first := true
		for _, s := range c.Steps {
			if s.Category != cat {
				continue
			}
			if first {
				p("## %s\n\n", cat)
				first = false
			}
			p("### %s\n\n", s.Op)
			p("**%s.** %s\n\n%s\n\n", s.Title, s.Description, s.Help)
			if s.Service {
				p("Needs a configured connection; Mai Studio skips it in local runs.\n\n")
			}
			fieldTable(&w, s.Fields, items)
			for _, short := range []struct {
				key  *string
				what string
			}{{s.Scalar, "a plain value"}, {s.List, "a list"}} {
				if short.key != nil && *short.key != "" {
					p("Short form: `%s:` followed by %s sets `%s`.\n\n", s.Op, short.what, *short.key)
				}
			}
			switch {
			case s.Form == "inline":
				p("```yaml\n- if: len(rows) > 0\n  then:\n    - log: Has rows.\n  else:\n    - log: Empty.\n```\n\n")
			case s.Example != "":
				p("```yaml\n- %s: %s\n```\n\n", s.Op, s.Example)
			}
		}
	}

	p("## Expression helpers\n\n")
	p("On top of [expr](https://expr-lang.org/docs/language-definition)'s built-ins.\n\n")
	p("| Helper | Result |\n| --- | --- |\n")
	for _, f := range c.Functions {
		p("| `%s` | %s |\n", f.Signature, f.Doc)
	}
	return w.String()
}

func fieldTable(w *strings.Builder, fields []FieldInfo, items map[string]ItemInfo) {
	fmt.Fprint(w, "| Key | Value | Required | Notes |\n| --- | --- | --- | --- |\n")
	for _, f := range fields {
		if f.Virtual {
			continue
		}
		key := "`" + f.Key + "`"
		if f.Key == "" {
			key = "(the argument)"
			if f.Rest {
				key = "(other keys)"
			}
		}
		required := "yes"
		if f.Optional || f.Kind == "bool" || f.Kind == "enum" {
			required = ""
		}
		notes := []string{}
		if len(f.Label) > 2 {
			notes = append(notes, strings.ToUpper(f.Label[:1])+f.Label[1:]+".")
		}
		if f.Hint != "" {
			notes = append(notes, f.Hint)
		}
		if f.Kind == "enum" && f.Fallback != "" {
			notes = append(notes, "Default: `"+f.Fallback+"`.")
		}
		fmt.Fprintf(w, "| %s | %s | %s | %s |\n", key, fieldValue(f, items), required, strings.Join(notes, " "))
	}
	fmt.Fprint(w, "\n")
}

// fieldValue says in a few words what a field holds.
func fieldValue(f FieldInfo, items map[string]ItemInfo) string {
	switch f.Kind {
	case "template":
		return "text with `{expression}` parts"
	case "number":
		if f.Integer {
			return "whole number"
		}
		return "number"
	case "bool":
		return "`true` or `false`"
	case "enum":
		if f.Boolean {
			return "`true` or `false`"
		}
		var values []string
		for _, o := range f.Options {
			if o[1] != "" {
				values = append(values, "`"+o[1]+"`")
			}
		}
		return strings.Join(values, ", ")
	case "list":
		return "list of names"
	case "expr":
		return f.Scope + " expression"
	case "entries":
		it := items[f.Item]
		if it.EntryKey != nil && it.EntryValue != nil {
			if len(it.EntryKey.Options) > 0 {
				var keys []string
				for _, o := range it.EntryKey.Options {
					keys = append(keys, "`"+o[1]+"`")
				}
				return strings.Join(keys, ", ") + ": each a " + fieldValue(*it.EntryValue, items)
			}
			return "map of name to " + fieldValue(*it.EntryValue, items)
		}
		return "map"
	case "items":
		var keys []string
		for _, sub := range items[f.Item].Fields {
			keys = append(keys, "`"+sub.Key+"`")
		}
		return "list of maps with " + strings.Join(keys, ", ")
	case "steps":
		return "list of steps"
	case "yaml":
		return "any YAML value"
	}
	return "text"
}
