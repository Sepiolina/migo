package workflow

import (
	"fmt"
	"strings"
)

// Schema returns a JSON Schema (draft-07) for workflow files, built from the
// step descriptors. Editors with YAML language support use it to complete
// step names and keys, show their help and flag unknown keys. It is
// deliberately loose about values (an expression can be any scalar): the
// parser, not the schema, decides whether a file is valid.
func Schema() map[string]any {
	c := Describe()
	b := schemaBuilder{items: map[string]ItemInfo{}}
	for _, it := range c.Items {
		b.items[it.Type] = it
	}
	step := map[string]any{}
	for _, s := range c.Steps {
		about := strings.TrimSpace(s.Title + ": " + s.Description + " " + s.Help)
		if s.Form == "inline" { // if / then / else are keys of the step itself
			for _, f := range s.Fields {
				step[f.Key] = b.field(f, about)
			}
			continue
		}
		step[s.Op] = b.argument(s, about)
	}
	object := func(props map[string]any, required ...string) map[string]any {
		o := map[string]any{"type": "object", "properties": props, "additionalProperties": false}
		if len(required) > 0 {
			o["required"] = required
		}
		return o
	}
	sheet := b.object(b.items["mai_sheet"].Fields)
	return map[string]any{
		"$schema":     "http://json-schema.org/draft-07/schema#",
		"title":       "Mai workflow",
		"description": "A MaiService workflow file. Generated by `migo schema`; see docs/WORKFLOWS.md.",
		"type":        "object",
		"required":    []string{"name", "input", "steps", "output"},
		"properties": map[string]any{
			"name": map[string]any{"type": "string", "description": "The workflow's name, shown in response messages."},
			"input": map[string]any{
				"type": "object", "minProperties": 1,
				"description": "One entry per uploaded file: a name for the steps, with an optional label and match.",
				"additionalProperties": map[string]any{"anyOf": []any{
					map[string]any{"type": "null"},
					object(map[string]any{
						"label": map[string]any{"type": "string", "description": "What the file is, for messages. Default: the name."},
						"match": map[string]any{"type": "string", "description": "A regular expression: this input takes the first uploaded file whose name matches."},
					}),
				}},
			},
			"steps": map[string]any{
				"type": "array", "minItems": 1, "items": map[string]any{"$ref": "#/definitions/step"},
				"description": "Run top to bottom on the current table.",
			},
			"service": described(b.object(b.items["mai_service"].Fields), b.items["mai_service"].Help),
			"output": object(map[string]any{
				"format": map[string]any{"enum": []string{"xlsx", "csv"}, "description": "The output file format. Default: xlsx. csv writes the one named sheet."},
				"sheets": map[string]any{
					"description": "The output sheets: a list of sheets, or the short form {Sheet name: dataset}.",
					"anyOf": []any{
						map[string]any{"type": "object", "additionalProperties": map[string]any{"type": "string"}},
						map[string]any{"type": "array", "items": sheet},
					},
				},
			}, "sheets"),
		},
		"additionalProperties": false,
		"definitions": map[string]any{
			"step": map[string]any{
				"type": "object", "minProperties": 1, "properties": step, "additionalProperties": false,
				"description": "One step: a `name: argument` pair, or if / then / else.",
			},
		},
	}
}

// scalarShortForm lists steps whose argument may also be a plain scalar
// that no field declares (`from: parts[Sheet]`).
var scalarShortForm = map[string]bool{"from": true}

type schemaBuilder struct{ items map[string]ItemInfo }

func described(s map[string]any, text string) map[string]any {
	if text != "" {
		s["description"] = text
	}
	return s
}

// argument is the schema of a step's YAML argument.
func (b schemaBuilder) argument(s StepInfo, about string) map[string]any {
	if len(s.Fields) == 1 && s.Fields[0].Key == "" { // the argument is the field itself
		return b.field(s.Fields[0], about)
	}
	alts := []any{b.object(s.Fields)}
	for _, key := range []*string{s.Scalar, s.List} {
		if key == nil {
			continue
		}
		for _, f := range s.Fields {
			if f.Key == *key && !f.Virtual {
				alts = append(alts, b.field(f, ""))
			}
		}
	}
	if scalarShortForm[s.Op] {
		alts = append(alts, map[string]any{"type": []string{"string", "number"}})
	}
	if len(alts) == 1 {
		return described(alts[0].(map[string]any), about)
	}
	return map[string]any{"description": about, "anyOf": alts}
}

// object is the schema of a map with one property per field; a key like
// "header.search" nests.
func (b schemaBuilder) object(fields []FieldInfo) map[string]any {
	props, required, open := map[string]any{}, []string{}, false
	nested, order := map[string][]FieldInfo{}, []string{}
	for _, f := range fields {
		switch head, rest, dotted := strings.Cut(f.Key, "."); {
		case f.Virtual:
		case f.Key == "" && f.Kind == "entries": // every other key of the map
			keys, value := b.entry(f)
			if keys == nil {
				open = true
			}
			for _, k := range keys {
				props[k] = value
			}
		case f.Key == "":
			open = true
		case dotted:
			if nested[head] == nil {
				order = append(order, head)
			}
			f.Key = rest
			nested[head] = append(nested[head], f)
		default:
			props[f.Key] = b.field(f, "")
			if !f.Optional && f.Kind != "bool" && f.Kind != "enum" {
				required = append(required, f.Key)
			}
		}
	}
	for _, head := range order {
		props[head] = b.object(nested[head])
	}
	o := map[string]any{"type": "object", "properties": props, "additionalProperties": open}
	if len(required) > 0 {
		o["required"] = required
	}
	return o
}

// entry returns the fixed keys of an entries field (nil: any key) and the
// schema of its values.
func (b schemaBuilder) entry(f FieldInfo) ([]string, map[string]any) {
	it := b.items[f.Item]
	if it.EntryKey == nil || it.EntryValue == nil {
		return nil, map[string]any{}
	}
	value := b.field(*it.EntryValue, it.Help)
	var keys []string
	for _, o := range it.EntryKey.Options {
		keys = append(keys, o[1])
	}
	return keys, value
}

// field is the schema of one field's value.
func (b schemaBuilder) field(f FieldInfo, about string) map[string]any {
	if about == "" {
		about = strings.TrimSpace(f.Label + ". " + f.Hint)
		if f.Label == "" || len(f.Label) < 3 {
			about = f.Hint
		}
	}
	s := map[string]any{}
	switch f.Kind {
	case "number":
		s["type"] = "number"
		if f.Integer {
			s["type"] = "integer"
		}
		if f.Min != nil {
			s["minimum"] = *f.Min
		}
	case "bool":
		s["type"] = "boolean"
	case "enum":
		if f.Boolean {
			s["type"] = "boolean"
			break
		}
		var values []string
		for _, o := range f.Options {
			if o[1] != "" {
				values = append(values, o[1])
			}
		}
		s["enum"] = values
	case "list":
		s["type"] = []string{"array", "string", "number"}
	case "entries":
		keys, value := b.entry(f)
		s["type"] = "object"
		if keys == nil {
			s["additionalProperties"] = value
		} else {
			props := map[string]any{}
			for _, k := range keys {
				props[k] = value
			}
			s["properties"], s["additionalProperties"] = props, false
		}
	case "items":
		s["type"], s["items"] = "array", b.object(b.items[f.Item].Fields)
		if about == "" {
			about = b.items[f.Item].Help
		}
	case "steps":
		s["type"], s["items"] = "array", map[string]any{"$ref": "#/definitions/step"}
	case "expr":
		about = strings.TrimSpace(fmt.Sprintf("%s (%s expression)", about, f.Scope))
	case "template":
		about = strings.TrimSpace(about + " (text with {expression} parts)")
	}
	return described(s, about)
}
